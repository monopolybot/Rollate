def match_card_text(extracted_text):
    """مقارنة النصوص المستخرجة مع قائمة البطاقات للـ 21 مجموعة"""
    found_cards = []
    for album_id, cards in ALBUMS_DATA.items():
        for card in cards:
            if card in extracted_text:
                found_cards.append({"album": album_id, "card": card})
    return found_cards
